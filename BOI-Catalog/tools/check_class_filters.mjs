import {chromium} from 'playwright';
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const site=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const out=path.resolve(site,'../_runtime/catalog');
await fs.mkdir(out,{recursive:true});
const base=process.env.BOI_CATALOG_URL||'http://127.0.0.1:8765';
const check=(condition,message)=>{if(!condition)throw new Error(message);};
const get=async(route)=>{const r=await fetch(base+route);check(r.ok,route);return r.json();};
const search=params=>get('/api/entries?'+new URLSearchParams(params));
const meta=await get('/api/meta');
check(meta.classes.length===6,'Six classes are required');
for(const category of ['weapons','armour','items','spiritequipment','tarotcards'])check(meta.classFilterCategories.includes(category),'Missing category '+category);
const specificWeapons={'1':68,'2':48,'3':48,'4':48,'5':48,'6':31};
for(const [id,count] of Object.entries(specificWeapons)){
 const result=await search({category:'weapons',class:id,shared:'0',limit:100});
 check(result.total===count,`Wrong specific weapon count for class ${id}`);
 check(result.items.every(e=>e.classIds.includes(id)&&e.classIds.length<6),'Wrong weapon class membership');
}
check((await search({category:'weapons',class:'shared'})).total===379,'Wrong shared weapon count');
check((await search({category:'weapons',class:'2'})).total===427,'Shared weapons must be included by default');
check((await search({category:'armour',class:'shared'})).total===1428,'Wrong shared armour count');
const physical=await search({category:'armour',q:'20131',class:'2',shared:'0'});
check(physical.items.some(e=>e.id==='20131'&&e.classIds.join(',')==='1,2,3'),'Physical multi-class armour is missing');
check(!(await search({category:'armour',q:'20131',class:'4',shared:'0'})).items.some(e=>e.id==='20131'),'Physical armour shown to Magus');
check((await search({category:'armour',q:'20152',class:'6',shared:'0'})).items.some(e=>e.id==='20152'&&e.classIds.join(',')==='4,5,6'),'Magic multi-class armour is missing');
check((await search({category:'items',q:'18000',class:'1',shared:'0'})).items.some(e=>e.id==='18000'),'Base item restrictions were not inherited by ItemID');
check(!(await search({category:'items',q:'18000',class:'2'})).items.some(e=>e.id==='18000'),'Wrong inherited ItemID class');
check((await search({category:'tarotcards',class:'6'})).total===1170,'Explicit Tarot ProfReq lists were not respected');
check((await search({category:'tarotcards',class:'6',shared:'0'})).total===0,'All-class Tarot cards must be removable');
check((await search({category:'monsters',class:'1'})).total===0,'Unknown class data must not be treated as universal');
check((await fetch(base+'/api/entries?category=weapons&class=99')).status===400,'Invalid class must be rejected');
const weapon=(await search({category:'weapons',q:'18000'})).items.find(e=>e.id==='18000');
const detail=(await get('/api/entry/'+encodeURIComponent(weapon.uid))).entry;
check(detail.fields['Классы']==='Берсерк'&&!('Класс' in detail.fields),'Detail uses the old class comment');
check((await search({category:'favorites',favorites:weapon.uid,class:'1'})).total===1,'Favorites class filter excludes valid entry');
check((await search({category:'favorites',favorites:weapon.uid,class:'2'})).total===0,'Favorites class filter includes invalid entry');
const compound=await search({category:'weapons',class:'2',shared:'0',min:'100',max:'120',images:'1',sort:'level'});
check(compound.total>0&&compound.items.every(e=>e.classIds.includes('2')&&e.classIds.length<6&&e.level>=100&&e.level<=120&&e.image),'Class/level/image filters do not compose');
const browser=await chromium.launch({headless:true,channel:process.env.BOI_BROWSER_CHANNEL||undefined});
try{
 const page=await browser.newPage({viewport:{width:1440,height:1050}}),errors=[];
 page.on('pageerror',error=>errors.push(error.message));
 const waitCount=async count=>page.waitForFunction(n=>document.querySelector('#results-text')?.textContent.endsWith('из '+Number(n).toLocaleString('ru-RU')),count);
 await page.goto(base+'/#weapons',{waitUntil:'networkidle'});
 await page.locator('#class-filter-row').waitFor({state:'visible'});
 await page.locator('#class-filter').selectOption('1');
 await waitCount(447);
 await page.locator('#include-shared').uncheck();
 await waitCount(68);
 await page.getByRole('button',{name:'2',exact:true}).click();
 await page.waitForFunction(()=>document.querySelectorAll('.entry-card').length===32);
 await page.locator('#class-filter').selectOption('2');
 await waitCount(48);
 check((await page.locator('#results-text').textContent()).includes('1–36'),'Changing class did not reset pagination');
 check((await page.locator('.card-class').allTextContents()).every(v=>v==='Рыцарь'),'Class badge mismatch');
 check(await page.locator('#filter-count').textContent()==='1','Class filter is not counted');
 await page.screenshot({path:path.join(out,'class-weapons-desktop.png'),animations:'disabled'});
 await page.locator('a[href="#armour"]').click();
 await waitCount(1001);
 check(await page.locator('#class-filter').inputValue()==='2','Class selection lost between equipment categories');
 check(!await page.locator('#include-shared').isChecked(),'Shared-item preference was lost');
 await page.locator('#class-filter').selectOption('shared');
 await waitCount(1428);
 check(await page.locator('#class-shared-toggle').isHidden(),'Irrelevant shared checkbox is visible');
 await page.locator('#filter-toggle').click();
 await page.locator('#reset-filters').click();
 await waitCount(6135);
 check(await page.locator('#class-filter').inputValue()==='','Reset did not clear class');
 await page.locator('#filter-toggle').click();
 await page.setViewportSize({width:390,height:844});
 await page.locator('#class-filter').selectOption('6');
 await page.locator('#include-shared').uncheck();
 await waitCount(434);
 await page.locator('#list-view').click();
 check(!await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),'Mobile class controls overflow');
 await page.screenshot({path:path.join(out,'class-armour-mobile.png'),animations:'disabled'});
 await page.locator('[data-open]').first().click();
 await page.locator('#detail-drawer:not([hidden])').waitFor();
 check((await page.locator('.detail-fields').textContent()).includes('Призыватель'),'Detail class not rendered');
 check(!await page.evaluate(()=>document.querySelector('#detail-drawer').scrollWidth>innerWidth),'Mobile detail overflow');
 await page.locator('#close-detail').click();
 await page.locator('#mobile-menu').click();
 await page.locator('a[href="#monsters"]').click();
 await waitCount(meta.categories.find(c=>c.key==='monsters').count);
 check(await page.locator('#class-filter-row').isHidden(),'Unsupported class filter is visible');
 check(errors.length===0,errors.join('\n'));
 console.log('PASS: six classes, authoritative restrictions, multi-class/shared equipment, related ItemIDs, combined filters, paging/reset, desktop and mobile');
}finally{await browser.close();}
