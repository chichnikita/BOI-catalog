import {chromium} from 'playwright';
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const here=path.dirname(fileURLToPath(import.meta.url));
const out=path.resolve(here,'../../_runtime/catalog');
await fs.mkdir(out,{recursive:true});
const base=process.env.BOI_CATALOG_URL||'http://127.0.0.1:8765';
const browser=await chromium.launch({headless:true,channel:process.env.BOI_BROWSER_CHANNEL||undefined});
const context=await browser.newContext({viewport:{width:1440,height:1050},deviceScaleFactor:1});
const page=await context.newPage();
const errors=[];
page.on('pageerror',error=>errors.push(error.message));
page.on('response',response=>{if(response.status()>=400)errors.push(response.status()+' '+response.url());});
await page.addInitScript(()=>{Object.defineProperty(navigator,'clipboard',{value:{writeText:async value=>{window.__copied=value;}}});});
await page.goto(base+'/',{waitUntil:'networkidle'});
await page.locator('.entry-card').first().waitFor();
await page.screenshot({path:path.join(out,'desktop-home.png'),fullPage:true});
let overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
if(overflow)throw new Error('Desktop horizontal overflow');
const initial=await page.locator('.entry-card').count();
await page.locator('a[href="#items"]').click();
await page.locator('#search').fill('63051');
await page.waitForFunction(()=>document.querySelector('#results')?.textContent.includes('LV1 Nova Deity Chest')&&document.querySelectorAll('.entry-card').length===1);
await page.locator('[data-open]').click();
await page.locator('#detail-drawer:not([hidden])').waitFor();
if(!(await page.locator('#detail-content').textContent()).includes('63051'))throw new Error('Detail ID missing');
await page.locator('#detail-copy').click();
if(await page.evaluate(()=>window.__copied)!=='63051')throw new Error('Copy failed');
await page.locator('#detail-favorite').click();
await page.screenshot({path:path.join(out,'desktop-detail.png'),fullPage:false});
await page.locator('#close-detail').click();
await page.locator('a[href="#favorites"]').click();
await page.waitForFunction(()=>document.querySelectorAll('.entry-card').length===1&&document.querySelector('.entry-card').textContent.includes('63051'));
await page.locator('#list-view').click();
if(!(await page.locator('#results').getAttribute('class')).includes('list-mode'))throw new Error('List view failed');
await page.locator('a[href="#monsters"]').click();
await page.locator('#boss-only').click();
await page.waitForFunction(()=>document.querySelector('#results-text')?.textContent.includes('549'));
await page.locator('#grid-view').click();
await page.screenshot({path:path.join(out,'desktop-bosses.png'),fullPage:false});
await page.locator('#search').fill('zz-no-such-boi-object-123');
await page.locator('.empty-state').waitFor();
await page.locator('[data-empty-reset]').click();
await page.locator('.entry-card').first().waitFor();
await page.locator('a[href="#commands"]').click();
await page.locator('#search').fill('additem');
await page.waitForFunction(()=>document.querySelectorAll('.entry-card').length===1&&document.querySelector('#results')?.textContent.includes('/additem'));
await page.locator('[data-open]').first().click();
await page.waitForFunction(()=>!document.querySelector('#detail-drawer').hidden&&document.querySelector('#detail-content h2')?.textContent==='/additem');
if(!(await page.locator('#detail-content').textContent()).includes('Выдача'))throw new Error('Russian command description missing');
await page.locator('#close-detail').click();
await page.locator('a.nav-item[href="#home"]').click();
await page.locator('#hero:not([hidden])').waitFor();
await page.setViewportSize({width:390,height:844});
await page.locator('#toast').waitFor({state:'hidden'});
await page.screenshot({path:path.join(out,'mobile-home.png'),fullPage:false,animations:'disabled'});
overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
if(overflow)throw new Error('Mobile horizontal overflow');
await page.locator('#mobile-menu').click();
await page.locator('#sidebar.open').waitFor();
await page.locator('a[href="#pets"]').click();
await page.locator('.entry-card').first().waitFor();
await page.locator('[data-open]').first().click();
await page.locator('#detail-drawer:not([hidden])').waitFor();
await page.screenshot({path:path.join(out,'mobile-detail.png'),fullPage:false});
if(errors.length)throw new Error('Browser errors: '+JSON.stringify(errors));
console.log(JSON.stringify({status:'PASS',initialCards:initial,checks:['search','detail','copy','favorites','list','boss-filter','empty-state','GM commands','mobile navigation','desktop and mobile overflow'],screenshots:5}));
await browser.close();
