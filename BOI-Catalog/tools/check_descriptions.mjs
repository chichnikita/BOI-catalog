import {chromium} from 'playwright';
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const out=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../../_runtime/catalog');
await fs.mkdir(out,{recursive:true});
const base=process.env.BOI_CATALOG_URL||'http://127.0.0.1:8765';
const get=async route=>{const r=await fetch(base+route);if(!r.ok)throw new Error(route);return r.json();};
const meta=await get('/api/meta');
if(meta.descriptionCount!==16034)throw new Error('Unexpected description coverage');
const find=async(category,id)=>(await get('/api/entries?'+new URLSearchParams({category,q:id}))).items.find(e=>e.id===id);
const crystal=await find('items','1');
const data=await get('/api/entry/'+encodeURIComponent(crystal.uid));
if(!data.entry.descriptions.ru.text.includes('Материал для усиления снаряжения'))throw new Error('Wrong Russian item tooltip');
if(!data.entry.descriptions.en.text.includes('Material to Fortify Gear'))throw new Error('Wrong English item tooltip');
if(data.entry.descriptions.ru.text.includes('<#')||data.entry.descriptions.ru.text.includes('\\n'))throw new Error('Unprocessed tooltip markup');
const browser=await chromium.launch({headless:true,channel:process.env.BOI_BROWSER_CHANNEL||undefined});
try{
 const context=await browser.newContext({viewport:{width:1440,height:1050}});
 const page=await context.newPage();const errors=[];page.on('pageerror',error=>errors.push(error.message));
 await page.goto(base+'/#items',{waitUntil:'networkidle'});
 await page.locator('#search').fill('Кристалл усиления');
 await page.waitForFunction(()=>[...document.querySelectorAll('.id-label b')].some(el=>el.textContent==='1'));
 await page.locator(`[data-open="${crystal.uid}"]`).click();
 await page.locator('.item-description-text').waitFor();
 if(!(await page.locator('.item-description-text').textContent()).includes('Материал для усиления'))throw new Error('RU description not rendered');
 await page.screenshot({path:path.join(out,'description-desktop.png')});
 await page.locator('[data-description-lang="en"]').click();
 if(!(await page.locator('.item-description-text').textContent()).includes('Material to Fortify Gear'))throw new Error('Language switch failed');
 await page.locator('[data-description-lang="ru"]').click();
 await page.locator('#close-detail').click();
 const gem=await find('gems','5001');
 await page.setViewportSize({width:390,height:844});
 await page.goto(base+'/#gems?entry='+encodeURIComponent(gem.uid),{waitUntil:'networkidle'});
 await page.locator('.item-description-text').waitFor();
 if(!(await page.locator('.item-description-text').textContent()).includes('10 ед.'))throw new Error('Gem effect missing');
 const overflow=await page.evaluate(()=>document.querySelector('#detail-drawer').scrollWidth>innerWidth);
 if(overflow)throw new Error('Description drawer overflow');
 await page.locator('.tooltip-heading').scrollIntoViewIfNeeded();
 await page.screenshot({path:path.join(out,'description-mobile.png'),animations:'disabled'});
 const missing=await find('weapons','18000');
 await page.goto(base+'/#weapons?entry='+encodeURIComponent(missing.uid),{waitUntil:'networkidle'});
 await page.locator('.tooltip-empty').waitFor();
 if(errors.length)throw new Error(errors.join('\n'));
 console.log('PASS: native Russian/English descriptions, Russian search, language switching, clean formatting, exact gem effect, mobile layout and honest missing-description state.');
}finally{await browser.close();}
